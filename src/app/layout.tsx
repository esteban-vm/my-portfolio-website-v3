import type { Metadata, Viewport } from 'next'
import { ThemeProvider } from '@teispace/next-themes'
import { getTheme, getThemeScriptProps } from '@teispace/next-themes/server'
import { NextIntlClientProvider } from 'next-intl'
import { getLocale } from 'next-intl/server'
import { Header } from '@/components'
import { THEME_COOKIE, THEME_STORAGE } from '@/lib/constants'
import { Axis, Geist, GoodTimes } from '@/lib/fonts'
import '@/styles/globals.css'

export const instant = false

export const metadata: Metadata = {
  title: 'Create Next App',
  description: 'Generated by create next app',
}

export const viewport: Viewport = {
  width: 'device-width',
  initialScale: 1,
  maximumScale: 1,
  userScalable: false,
  viewportFit: 'cover',
}

export default async function RootLayout({ children }: LayoutProps<'/'>) {
  const locale = await getLocale()
  const initialTheme = (await getTheme()) ?? ''

  return (
    <html
      className={`${Axis.variable} ${Geist.variable} ${GoodTimes.variable} h-full antialiased`}
      dir='ltr'
      lang={locale}
      suppressHydrationWarning
    >
      <head>
        <script {...getThemeScriptProps({ attribute: 'class', initialTheme })} />
      </head>
      <body className='relative h-full'>
        <ThemeProvider
          attribute='class'
          cookieOptions={{ name: THEME_COOKIE }}
          defaultTheme='system'
          disableTransitionOnChange
          enableColorScheme={false}
          enableSystem
          initialTheme={initialTheme}
          noScript
          storage='hybrid'
          storageKey={THEME_STORAGE}
          themes={['light', 'dark']}
        >
          <NextIntlClientProvider>
            <div className='fixed inset-0 size-full overflow-auto bg-background text-foreground'>
              <div className='relative mx-auto flex min-h-full w-full max-w-7xl flex-col px-2 font-geist'>
                <Header />
                {children}
                <footer className='mb-2 shrink-0 grow-0 rounded-2xl border border-foreground/30 text-center'>
                  Footer
                </footer>
              </div>
            </div>
          </NextIntlClientProvider>
        </ThemeProvider>
      </body>
    </html>
  )
}
